function ServiceTile({ category, openKey, onToggle }) {
  return (
    <div className="service__item">
      <div className="service__img-container">
        {category.images.map((img, i) => (
          <img key={i} className="service__img" src={img.src} alt={img.alt} />
        ))}
      </div>
      <h3 className="service__subtitle">{category.title}</h3>
      {category.intro && <p className="service__intro">{category.intro}</p>}
      <ul className="service__list">
        {category.items.map((item, index) => {
          const key = `${category.id}-${index}`;
          const isOpen = openKey === key;
          return (
            <li key={item.name} className="service__list-item">
              <button
                type="button"
                className="service__list-item_button"
                aria-expanded={isOpen}
                onClick={() => onToggle(key)}
              >
                <span className="service__list-item_span">{item.name}</span>
                <span className={`service__list-item_arrow${isOpen ? ' service__list-item_arrow--open' : ''}`}>▾</span>
              </button>
              <div className={`service__accordion${isOpen ? ' service__accordion--open' : ''}`}>
                <p className="service__accordion-text">{item.desc}</p>
              </div>
            </li>
          );
        })}
      </ul>
    </div>
  );
}

function Service() {
  const [openKey, setOpenKey] = useState(null);

  const handleToggle = (key) => {
    setOpenKey((prev) => (prev === key ? null : key));
  };

  return (
    <section className="service content__section" id="service">
      <h2 className="section__title">Услуги</h2>
      {services.map((category) => (
        <ServiceTile
          key={category.id}
          category={category}
          openKey={openKey}
          onToggle={handleToggle}
        />
      ))}
    </section>
  );
}

export default Service;